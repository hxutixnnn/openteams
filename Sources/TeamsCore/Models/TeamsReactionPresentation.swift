    public static func symbol(for key: String) -> String {
        if key.lowercased() == "grinningfacewithsmilingeyes" { return "😄" }
        if key.lowercased() == "ok" { return "👌" }
        if let value = aliases[key.lowercased()] { return value }
        let parts = key.lowercased().split(separator: "_", omittingEmptySubsequences: false)
        var scalars = String.UnicodeScalarView()
        for part in parts {
            guard (4...6).contains(part.count), part.allSatisfy({ $0.isHexDigit }),
                  let number = UInt32(part, radix: 16), let scalar = UnicodeScalar(number) else { break }
            guard allowedEmojiScalar(scalar) else { return "✦" }
            scalars.append(scalar)
        }
        if !scalars.isEmpty, scalars.first?.properties.isEmoji == true {
            return String(scalars)
        }
        if key.count <= 16, !key.isEmpty, key.unicodeScalars.allSatisfy(allowedEmojiScalar),
           key.unicodeScalars.first?.properties.isEmoji == true { return key }
        return "✦"
    }

    private static func allowedEmojiScalar(_ scalar: UnicodeScalar) -> Bool {
        let value = scalar.value
        return (value > 127 && scalar.properties.isEmoji) || value == 0x200d || value == 0xfe0e || value == 0xfe0f ||
            value == 0x20e3 || (0xe0020...0xe007f).contains(value)
    }

    public static func name(for key: String) -> String {
        let known = ["like": "Like", "heart": "Love", "laugh": "Laugh", "surprised": "Surprised", "skull": "Skull", "grinningfacewithsmilingeyes": "Grinning face with smiling eyes", "ok": "OK"]
        if let value = known[key.lowercased()] { return value }
        let symbol = symbol(for: key)
        if symbol != "✦", let unicodeName = symbol.unicodeScalars.first?.properties.name {
            return unicodeName.lowercased().capitalized
        }
        let parts = key.split(separator: "_").drop(while: { part in
